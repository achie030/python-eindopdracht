# Cijfers van drie vakken
cijfer1 = 7
cijfer2 = 6
cijfer3 = 8

# Gemiddelde berekenen
gemiddelde = (cijfer1 + cijfer2 + cijfer3) / 3

print("Gemiddelde:", gemiddelde)

# Controleren of student geslaagd is
